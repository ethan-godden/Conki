// Assembles dist/, which holds everything that goes into Anki:
//
//   dist/front.html, dist/back.html   note type > Cards > Front / Back Template
//   dist/style.css                    note type > Cards > Styling
//   dist/media/_code-card.js          the profile's collection.media folder
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src");
const dist = join(root, "dist");
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));

await rm(dist, { recursive: true, force: true });
await mkdir(join(dist, "media"), { recursive: true });

// The script: the modules in src/js and the libraries they import, compiled
// into one plain script.
const script = join(dist, "media/_code-card.js");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/js/index.js"],
  outfile: script,
  bundle: true,
  format: "iife",
  target: "es2018",
  minify: true,
  legalComments: "none",
  define: { __VERSION__: JSON.stringify(pkg.version) },
  banner: { js: `/* ${pkg.name} ${pkg.version}: generated by "npm run build". Edit the sources in src/js, not this file. */` },
  metafile: true,
  logLevel: "warning",
});
await writeFile(script, escapeNonAscii(await readFile(script, "utf8")) + (await thirdPartyNotices(result.metafile)));

await writeFile(join(dist, "front.html"), await template("front.html"));
await writeFile(join(dist, "back.html"), await template("back.html"));
await copyFile(join(src, "style.css"), join(dist, "style.css"));

for (const entry of await readdir(dist, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile()) continue;
  const file = join(entry.parentPath, entry.name);
  console.log(`${relative(root, file)}  ${((await stat(file)).size / 1024).toFixed(1)} kB`);
}

/* A card template with every <script data-inline src="file"></script> replaced
 * by an inline script holding that file's contents. Anki templates cannot
 * share a file, so the loader both templates need is kept once in
 * src/templates and copied into each here. */
async function template(name) {
  const tag = /<script data-inline src="([^"]+)"><\/script>/g;
  const html = await readFile(join(src, "templates", name), "utf8");
  const scripts = new Map();
  for (const [, file] of html.matchAll(tag)) {
    const code = await readFile(join(src, "templates", file), "utf8");
    if (/<\/script/i.test(code)) throw new Error(`${file} contains "</script", which would end the inline script early`);
    scripts.set(file, code.replace(/^\/\*[\s\S]*?\*\/\n/, ""));   // drop the file's leading comment
  }
  return html.replace(tag, (match, file) => `<script>\n${scripts.get(file)}</script>`);
}

/* esbuild escapes non-ASCII characters in strings but leaves them in regular
 * expressions. Escape those too, so the script means the same whatever
 * encoding it is read with. */
function escapeNonAscii(code) {
  return code.replace(/[^\x00-\x7F]/g, (ch) => "\\u" + ch.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0"));
}

/* The licence of every npm package that ended up in the bundle, as a comment
 * to append to it, so the notices travel with the file. A package that was
 * read but whose code was all dropped (tree shaking) is not in the file. */
async function thirdPartyNotices(metafile) {
  const dirs = new Set();
  for (const output of Object.values(metafile.outputs)) {
    for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
      const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
      if (match && bytesInOutput > 0) dirs.add(match[1]);
    }
  }
  const notices = [];
  for (const dir of dirs) {
    const abs = join(root, dir);
    const meta = JSON.parse(await readFile(join(abs, "package.json"), "utf8"));
    const file = (await readdir(abs)).find((name) => /^licen[cs]e/i.test(name));
    const text = file ? await readFile(join(abs, file), "utf8") : "(the package ships no licence file)";
    notices.push({ name: meta.name, text: `----- ${meta.name} ${meta.version} (${meta.license}) -----\n\n${text.trim()}` });
  }
  if (!notices.length) return "";
  notices.sort((a, b) => a.name.localeCompare(b.name));
  const body = notices.map((notice) => notice.text).join("\n\n")
    .replace(/\r\n?/g, "\n")
    .replace(/\*\//g, "* /")                                  // must not end the comment
    .replace(new RegExp(String.fromCharCode(169), "g"), "(c)")
    .replace(/[^\x00-\x7F]/g, "?");                           // keep the file plain ASCII
  return `\n/*\nThird-party code compiled into this file, with its licences.\n\n${body}\n*/\n`;
}
