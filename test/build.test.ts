import assert from "node:assert/strict";
import { readdir, readFile } from "node:fs/promises";
import test from "node:test";
import { JSDOM } from "jsdom";
import { built } from "./helpers/reviewer.ts";

const root = new URL("../", import.meta.url);
const pkg = JSON.parse(await readFile(new URL("package.json", root), "utf8"));
const NON_ASCII = /[^\x00-\x7F]/;

test("dist holds exactly the files that go into Anki", async () => {
  const files = (await readdir(new URL("dist/", root), { recursive: true, withFileTypes: true }))
    .filter((entry) => entry.isFile()).map((entry) => entry.name).sort();
  assert.deepEqual(files, ["_code-card.js", "back.html", "front.html", "style.css"]);
});

test("the script is plain ASCII, so it does not depend on how it is decoded", () => {
  assert.equal(NON_ASCII.test(built.script), false);
});

test("the script says what it is and carries no source-map reference", () => {
  assert.ok(built.script.startsWith(`/* ${pkg.name} ${pkg.version}: generated by`));
  assert.equal(/sourceMappingURL/.test(built.script), false);
});

test("the licences of the bundled libraries are in the script", async () => {
  for (const name of ["markdown-it", "@codemirror/view", "@codemirror/state", "@codemirror/commands", "@codemirror/merge"]) {
    const { version } = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), "utf8"));
    assert.ok(built.script.includes(`----- ${name} ${version} (`), `licence notice for ${name} ${version}`);
  }
});

test("a library the build read but dropped completely has no notice", () => {
  assert.equal(built.script.includes("----- @codemirror/streamparser "), false);
});

test("running the script defines CodeCard and nothing else it did not have to", () => {
  const { window } = new JSDOM("", { runScripts: "outside-only" });
  const before = new Set(Object.keys(window));
  window.eval(built.script);
  assert.deepEqual(Object.keys(window).filter((key) => !before.has(key)), ["CodeCard"]);
  assert.deepEqual(Object.keys(window.CodeCard!).sort(), ["config", "render", "version"]);
  assert.equal(window.CodeCard!.version, pkg.version);
});

test("running the script twice keeps the first CodeCard", () => {
  const { window } = new JSDOM("", { runScripts: "outside-only" });
  window.eval(built.script);
  const first = window.CodeCard;
  window.eval(built.script);
  assert.equal(window.CodeCard, first);
});

test("the loader is inlined into both templates", () => {
  const script = (html: string) => /<script>\n([\s\S]*?)<\/script>/.exec(html)![1];
  for (const html of [built.front, built.back]) {
    assert.equal(/data-inline/.test(html), false);
    assert.equal(html.match(/<script/g)!.length, 1);
    assert.match(script(html), /CodeCard\.render\(root\)/);
  }
  assert.equal(script(built.front), script(built.back));
});

test("the templates use the fields the note type has", () => {
  const used = (html: string) => [...new Set([...html.matchAll(/\{\{[#^/]?([^}]+)\}\}/g)].map((match) => match[1]))].sort();
  assert.deepEqual(used(built.front), ["Answer", "Prompt"]);
  assert.deepEqual(used(built.back), ["Answer", "Back", "Prompt"]);
  assert.match(built.back, /id="answer"/, "Anki scrolls to this element on the answer side");
});

test("sources contain only ASCII: no invisible or look-alike characters", async () => {
  for (const dir of ["src/", "scripts/", "test/"]) {
    for (const entry of await readdir(new URL(dir, root), { recursive: true, withFileTypes: true })) {
      if (!entry.isFile() || entry.name.startsWith(".")) continue;   // not .DS_Store and the like
      const file = `${entry.parentPath}/${entry.name}`;
      const line = (await readFile(file, "utf8")).split("\n").findIndex((text) => NON_ASCII.test(text));
      assert.equal(line, -1, `${file}:${line + 1} has a non-ASCII character; write it as an escape such as \\u00A0`);
    }
  }
});
